const connection = await mysql.createConnection({
  uri: process.env.DATABASE_URL,
  charset: "utf8mb4",
});

const updated = [];
const notFound = [];
try {
  await connection.beginTransaction();
  for (const [
    email,
    code,
    name,
    jira,
    citizenId,
    phone,
    birthday,
    address,
    issuedDate,
  ] of rows) {
    const [result] = await connection.execute(
      `UPDATE users
       SET code=?, name=?, jira_account=?, citizen_id=?, phone=?, birthday=?,
           address=COALESCE(?, address),
           citizen_issued_date=COALESCE(?, citizen_issued_date),
           updated_at=NOW(3)
       WHERE LOWER(TRIM(email))=LOWER(TRIM(?))`,
      [
        code,
        name,
        jira,
        citizenId,
        phone,
        birthday,
        address,
        issuedDate,
        email,
      ],
    );
    if (result.affectedRows) updated.push(email);
    else notFound.push(email);
  }
  await connection.commit();
  console.log(`Updated: ${updated.length}/${rows.length}`);
  if (notFound.length) console.log(`Not found: ${notFound.join(", ")}`);
} catch (error) {
  await connection.rollback();
  throw error;
} finally {
  await connection.end();
}
